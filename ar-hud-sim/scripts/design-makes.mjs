// Searches each make's design choices with the full tracer and keeps the
// best-scoring design. Writes js/config/makes.tuned.js.
// Usage: node scripts/design-makes.mjs [evals-per-make]
import { writeFileSync } from 'node:fs';
import { MAKES, buildMake, applyPrintedCosts } from '../js/config/makes.js';
import { runSimulation } from '../js/optics/Simulation.js';
import { analyzeCoverage } from '../js/optics/CoverageAnalyzer.js';
import { runDiagnostics } from '../js/optics/Diagnostics.js';
import { scoreDesign } from '../js/optics/Scorecard.js';
import { reachPoints, evaluateAim } from '../js/optics/reach.js';
import { TUNED as PREVIOUS } from '../js/config/makes.tuned.js';
import { SEEDS } from '../js/config/makes.seeds.js';

const EVALS = Number(process.argv[2] ?? 260);
const ONLY = process.argv[3]; // optional: search only this make, keep the others' stored results

export function evaluate(make, v) {
  const p = buildMake(make, v);
  const r = runSimulation(p);          // default sampling: what the page shows
  applyPrintedCosts(p);
  const cov = analyzeCoverage(r);
  const d = runDiagnostics(r, cov);
  const s = scoreDesign(r, cov, d, p);
  // tie-breakers inside a score level: wider visible field, then lighter
  const met = s.goals.filter((g) => g.met).length;
  // a housing that does not connect to the temple would float: never accept it
  const floating = d.checks.some((c) => c.id === 'shellJoined' && c.status !== 'pass');
  const obj = s.overall - (floating ? 1 : 0) + 0.05 * met + 0.002 * (cov.field.hfov ?? 0) - 0.0005 * s.totals.grams;
  return { v, s, obj, fov: cov.field.hfov, vfov: cov.field.vfov };
}

let seed = 12345;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const lerp = ([a, b], t) => a + (b - a) * t;
const round = (x, d = 1) => Math.round(x * 10 ** d) / 10 ** d;

function randomVars(make) {
  const V = make.vars, out = {};
  for (const [k, r] of Object.entries(V)) out[k] = typeof r[0] !== 'number' || r.length !== 2 || k === 'prism' ? pick(r) : round(lerp(r, rnd()));
  return out;
}
function mutate(make, v, scale) {
  const V = make.vars, out = { ...v };
  const keys = Object.keys(V);
  const n = 1 + Math.floor(rnd() * 3);
  for (let i = 0; i < n; i++) {
    const k = pick(keys), r = V[k];
    if (typeof r[0] !== 'number' || r.length !== 2 || k === 'prism') out[k] = pick(r);
    else out[k] = round(Math.min(r[1], Math.max(r[0], out[k] + (rnd() * 2 - 1) * scale * (r[1] - r[0]))));
  }
  return out;
}

const tuned = {};
if (process.env.NO_SEARCH) process.exit(0);
for (const make of MAKES) {
  if (ONLY && make.id !== ONLY && PREVIOUS[make.id]) { tuned[make.id] = PREVIOUS[make.id]; continue; }
  const t0 = Date.now();
  let best = null;
  // warm start: earlier good designs for this make are candidates too
  const warm = [PREVIOUS[make.id]?.vars, ...(SEEDS[make.id] ?? [])].filter(Boolean);
  const nRandom = Math.round(EVALS * 0.35);
  for (let i = 0; i < EVALS + warm.length; i++) {
    const v = i < warm.length ? { ...randomVars(make), ...warm[i] } : (i - warm.length < nRandom || !best ? randomVars(make) : mutate(make, best.v, i < EVALS * 0.75 ? 0.25 : 0.08));
    let e;
    try { e = evaluate(make, v); } catch (err) { continue; }
    if (!best || e.obj > best.obj) best = e;
  }
  const g = Object.fromEntries(best.s.goals.map((x) => [x.id, x]));
  console.log(`${make.name.padEnd(8)} overall ${(100 * best.s.overall).toFixed(1)}% | pupil ${g.pupil.value} | ${g.weight.value} | ${g.cost.value} | structure ${g.structure.value} | FOV ${best.fov?.toFixed(1)}×${best.vfov?.toFixed(1)} | ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  console.log('         vars', JSON.stringify(best.v));
  const fails = best.s.structural.filter((x) => !x.ok).map((x) => `${x.label}: ${x.value}`);
  if (fails.length) console.log('         failing:', fails.join(' | '));
  const bp = buildMake(make, best.v);
  const reach = reachPoints(bp.targets.zone).map((pt) => { const e = evaluateAim(bp, pt.h, pt.v); return { h: +e.h.toFixed(1), v: +e.v.toFixed(1), visible: +e.visible.toFixed(3), buildable: e.buildable, failed: e.failed }; });
  console.log('         reach:', reach.filter((x) => x.buildable && x.visible >= 0.999).length, '/', reach.length, 'aim points fully visible + buildable');
  tuned[make.id] = { reach, vars: best.v, overall: best.s.overall, goals: best.s.goals.map(({ id, value, score, met }) => ({ id, value, score, met })), fov: [best.fov, best.vfov] };
}
writeFileSync(new URL('../js/config/makes.tuned.js', import.meta.url),
  `// Generated by scripts/design-makes.mjs (${EVALS} evaluations per make). Do not edit by hand.\nexport const TUNED = ${JSON.stringify(tuned, null, 2)};\n`);
